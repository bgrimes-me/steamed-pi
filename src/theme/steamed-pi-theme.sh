#!/bin/bash
# Apply (or undo) the Steamed Pi look on the GNOME desktop + terminal.
#   steamed-pi-theme.sh apply [wallpaper.png]     default wallpaper: ~/.local/share/steamed-pi/art/brand/wallpaper-1080p.png
#   steamed-pi-theme.sh undo                      restores the settings saved before the first apply
# Safe to re-run. Touches only appearance settings (wallpaper, dark mode, accent, themes, terminal colors).
set -u
HERE=$(dirname "$(readlink -f "$0")"); . "$HERE/palette.conf"
BK=$HOME/.local/state/steamed-pi/theme-backup; PATHS=(/org/gnome/desktop/interface/ /org/gnome/desktop/background/ /org/gnome/desktop/screensaver/ /org/gnome/terminal/)
name() { echo "$1" | tr '/' '_'; }
# individual keys we change (their dconf paths are too big to back up and reset wholesale)
KEYFILE=$BK/keys.txt
KEYS=("org.gnome.shell favorite-apps" "org.gnome.shell.extensions.dash-to-dock show-trash" "org.gnome.shell.extensions.ding show-home")
case "${1:-apply}" in
  undo)
    [ -d "$BK" ] || { echo "no backup found in $BK"; exit 1; }
    for p in "${PATHS[@]}"; do dconf reset -f "$p"; [ -s "$BK/$(name $p).ini" ] && dconf load "$p" < "$BK/$(name $p).ini"; done
    if [ -f "$KEYFILE" ]; then while IFS=$'\t' read -r schema key val; do gsettings set "$schema" "$key" "$val" 2>/dev/null; done < "$KEYFILE"; fi
    sed -i "/# >>> steamed-pi prompt >>>/,/# <<< steamed-pi prompt <<</d" ~/.bashrc; rm -f ~/.config/steamed-pi/prompt.sh
    rm -f "$HOME/.local/share/icons/Yaru/scalable/actions/view-app-grid-ubuntu-symbolic.svg"; gsettings set org.gnome.desktop.interface icon-theme "$(gsettings get org.gnome.desktop.interface icon-theme | tr -d "'")" 2>/dev/null
    echo "restored the previous appearance settings"; exit 0 ;;
  apply) ;;
  *) sed -n '2,6p' "$0"; exit 2 ;;
esac
WP=${2:-$HOME/.local/share/steamed-pi/art/brand/wallpaper-1080p.png}; [ -f "$WP" ] || { echo "wallpaper not found: $WP"; exit 1; }
if [ ! -d "$BK" ]; then mkdir -p "$BK"; for p in "${PATHS[@]}"; do dconf dump "$p" > "$BK/$(name $p).ini"; done; echo "saved your current settings to $BK"; fi
mkdir -p ~/.local/share/backgrounds; DEST=$HOME/.local/share/backgrounds/$(basename "$WP"); cp -f "$WP" "$DEST"; URI="file://$DEST"
# wallpaper (desktop + lock screen)
gsettings set org.gnome.desktop.background picture-uri "$URI"; gsettings set org.gnome.desktop.background picture-uri-dark "$URI"
gsettings set org.gnome.desktop.background picture-options zoom; gsettings set org.gnome.desktop.background primary-color "$BG_DESKTOP"; gsettings set org.gnome.desktop.background secondary-color "$BG_DESKTOP"
gsettings set org.gnome.desktop.screensaver picture-uri "$URI"; gsettings set org.gnome.desktop.screensaver picture-options zoom; gsettings set org.gnome.desktop.screensaver primary-color "$BG_DESKTOP"
# dark mode + amber accent
gsettings set org.gnome.desktop.interface color-scheme prefer-dark; gsettings set org.gnome.desktop.interface accent-color "$GNOME_ACCENT"
gsettings set org.gnome.desktop.interface gtk-theme "$GTK_THEME"; gsettings set org.gnome.desktop.interface icon-theme "$ICON_THEME"
# gnome-terminal: default profile
P=$(gsettings get org.gnome.Terminal.ProfilesList default | tr -d "'"); S="org.gnome.Terminal.Legacy.Profile:/org/gnome/terminal/legacy/profiles:/:$P/"
gsettings set $S use-theme-colors false; gsettings set $S background-color "$BG_TERMINAL"; gsettings set $S foreground-color "$TEXT"
gsettings set $S palette "[$PALETTE]"; gsettings set $S bold-color-same-as-fg true; gsettings set $S bold-is-bright false
gsettings set $S cursor-colors-set true; gsettings set $S cursor-background-color "$ACCENT"; gsettings set $S cursor-foreground-color "$BG_TERMINAL"
gsettings set $S highlight-colors-set true; gsettings set $S highlight-background-color "$ACCENT"; gsettings set $S highlight-foreground-color "$BG_TERMINAL"
gsettings set $S use-theme-transparency false; gsettings set $S use-transparent-background false
# desktop defaults: dock pins only what a console needs; no trash in the dock, no Home icon on the desktop
mkdir -p "$BK"
if [ ! -f "$KEYFILE" ]; then for k in "${KEYS[@]}"; do set -- $k; v=$(gsettings get "$1" "$2" 2>/dev/null) && printf '%s\t%s\t%s\n' "$1" "$2" "$v" >> "$KEYFILE"; done; fi
gsettings set org.gnome.shell favorite-apps "['firefox_firefox.desktop', 'org.gnome.Nautilus.desktop', 'org.gnome.Terminal.desktop', 'steam-native.desktop', 'steamed-pi-gaming-mode.desktop']" 2>/dev/null
gsettings set org.gnome.shell.extensions.dash-to-dock show-trash false 2>/dev/null
gsettings set org.gnome.shell.extensions.ding show-home false 2>/dev/null
# shell prompt in the palette colors: amber user@host, tan path (instead of Ubuntu's green and blue)
rgb() { local h=${1#\#}; printf '%d;%d;%d' 0x${h:0:2} 0x${h:2:2} 0x${h:4:2}; }
mkdir -p ~/.config/steamed-pi
cat > ~/.config/steamed-pi/prompt.sh <<PROMPT
# generated by steamed-pi-theme.sh from palette.conf (ACCENT, TAN). Remove with: steamed-pi-theme.sh undo
case "\$TERM" in
  xterm-color|*-256color|xterm-kitty|alacritty|foot|tmux*|screen*)
    PS1='\\[\\e]0;\${debian_chroot:+(\$debian_chroot)}\\u@\\h: \\w\\a\\]\${debian_chroot:+(\$debian_chroot)}\\[\\e[1;38;2;$(rgb "$ACCENT")m\\]\\u@\\h\\[\\e[0m\\]:\\[\\e[38;2;$(rgb "$TAN")m\\]\\w\\[\\e[0m\\]\\\$ ' ;;
esac
PROMPT
if ! grep -q '>>> steamed-pi prompt >>>' ~/.bashrc; then printf '\n# >>> steamed-pi prompt >>>\n[ -f ~/.config/steamed-pi/prompt.sh ] && . ~/.config/steamed-pi/prompt.sh\n# <<< steamed-pi prompt <<<\n' >> ~/.bashrc; fi
# dock "Show Applications" button: the btgprojects cursor bar instead of the Ubuntu logo
IC=$HOME/.local/share/steamed-pi/art/brand/app-grid-icon.svg
if [ -f "$IC" ]; then mkdir -p "$(dirname "$HOME/.local/share/icons/Yaru/scalable/actions/view-app-grid-ubuntu-symbolic.svg")" && cp -f "$IC" "$HOME/.local/share/icons/Yaru/scalable/actions/view-app-grid-ubuntu-symbolic.svg"; T=$(gsettings get org.gnome.desktop.interface icon-theme | tr -d "'"); gsettings set org.gnome.desktop.interface icon-theme Yaru-yellow; sleep 1; gsettings set org.gnome.desktop.interface icon-theme "$T"; fi
echo "Steamed Pi theme applied (wallpaper, dark mode, $GNOME_ACCENT accent, terminal colors)"
